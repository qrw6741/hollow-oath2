#!/usr/bin/env python3
"""Generates: 11 Descent armours, 8 consumables + 11 keepsakes, the Wayfarer NPC conversations
(systems/descent_npcs.gd) and patches the registries. Idempotent.  Run: python3 tools/gen_descent2.py"""
import os, re, sys
R = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(R, "tools"))
import descent2_data as D
import expansion_data as XD


def col(h):
    h = h.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return f"Color({r:.3f}, {g:.3f}, {b:.3f}, 1)"


def q(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def patch_ids(path, ids):
    s = open(path).read()
    add = [i for i in ids if f'&"{i}"' not in s]
    if add:
        s = re.sub(r"(const IDS: Array\[StringName\] = \[.*?)(\])", lambda m: m.group(1).rstrip().rstrip(",") + ", " + ", ".join(f'&"{i}"' for i in add) + m.group(2), s, count=1, flags=re.S)
        open(path, "w").write(s)


# ---- armours
for (aid, name, look, dmg, spd, res, dodge, cloth, light, acc, desc) in D.ARMORS:
    rs = "{" + ", ".join(f'"{k}": {v}' for k, v in res.items()) + "}"
    open(f"{R}/data/armors/{aid}.tres", "w").write(f'''[gd_resource type="Resource" script_class="ArmorData" load_steps=2 format=3]

[ext_resource type="Script" path="res://systems/armor_data.gd" id="1_armor"]

[resource]
script = ExtResource("1_armor")
id = &"{aid}"
display_name = "{q(name)}"
description = "{q(desc)}"
look = {look}
damage_taken_mult = {dmg}
run_speed_mult = {spd}
dodge_stamina_add = {dodge}
cloth_color = {col(cloth)}
cloth_light_color = {col(light)}
accent_color = {col(acc)}
resist = {rs}
''')
patch_ids(f"{R}/systems/armors.gd", [a[0] for a in D.ARMORS])


# ---- items
def item(id_, name, desc, colr, kind, effect, amount, stack):
    open(f"{R}/data/items/{id_}.tres", "w").write(f'''[gd_resource type="Resource" script_class="ItemData" load_steps=2 format=3]

[ext_resource type="Script" path="res://systems/items/item_data.gd" id="1_item"]

[resource]
script = ExtResource("1_item")
id = &"{id_}"
display_name = "{q(name)}"
description = "{q(desc)}"
kind = {kind}
effect = {effect}
effect_amount = {amount}
max_stack = {stack}
icon_color = {colr}
''')


for (i, n, d, c, e, a, s) in D.ITEMS:
    item(i, n, d, c, 0, e, a, s)
KEEP = []
for np in D.NPCS:
    gid, gname, gdesc = np["gift"]
    item(gid, gname, gdesc, "Color(0.85, 0.78, 0.55, 1)", 2, 0, 0.0, 1)
    KEEP.append(gid)
patch_ids(f"{R}/systems/items/items.gd", [x[0] for x in D.ITEMS] + KEEP)

# ---- NPC conversations
def arr(xs):
    return "[" + ", ".join(f'"{q(x)}"' for x in xs) + "]"


rows = []
for np in D.NPCS:
    boss = XD.BOSSES[np["map"]][2]["id"]
    rows.append(f'''	&"{np["id"]}": {{"speaker": "{q(np["name"])}", "map": &"{XD.MAPS[np["map"]]["key"]}", "boss": &"{boss}", "gift": &"{np["gift"][0]}",
		"first": {arr(np["first"])},
		"greet": {arr(np["greet"])},
		"after": {arr(np["after"])}}},''')
shops = []
for k, (nm, stock) in D.SHOPS.items():
    shops.append(f'	&"{k}": {{"name": "{q(nm)}", "stock": [' + ", ".join('{"item": &"%s", "price": %d}' % (i, p) for i, p in stock) + "]},")
vrows = [f'	&"{k}": "{q(v)}",' for k, v in D.VESPER.items()]
for i, mp in enumerate(XD.MAPS):
    b = XD.BOSSES[i][2]
    vrows.append(f'	&"relic_x_{b["id"]}": "{q(D.RELIC_NAMES[i] + ". " + b["lore"] + " I would wear it myself, but archivists are meant to keep things, not use them.")}",')
open(f"{R}/systems/descent_npcs.gd", "w").write(f'''class_name DescentNpcs
extends RefCounted
## GENERATED by tools/gen_descent2.py from tools/descent2_data.py. The Wayfarers of the Descent: one
## person per new map, with a first meeting, passing greetings, and (once the map's main boss is
## down) a farewell that gives a keepsake. State is world flags (no save change):
##   talks_<id> (count, shared with Dialogues)   dn_after_<id> = true once the farewell was heard

const DATA := {{
{chr(10).join(rows)}
}}
## What Vesper says about a keepsake or relic of the Descent (merged into Dialogues.archive_pending).
const ARCHIVE := {{
{chr(10).join(vrows)}
}}
const SHOPS := {{
{chr(10).join(shops)}
}}


static func has(npc: StringName) -> bool:
	return DATA.has(npc)


static func farewell_due(npc: StringName) -> bool:
	if not DATA.has(npc):
		return false
	return bool(GameState.get_flag(StringName("boss_defeated_" + String(DATA[npc].boss)), false)) and not bool(GameState.get_flag(StringName("dn_after_" + String(npc)), false)) and Dialogues.talks(npc) > 0


static func conversation(npc: StringName) -> Dictionary:
	var d: Dictionary = DATA[npc]
	var n := Dialogues.talks(npc)
	if n == 0:
		return {{"speaker": d.speaker, "lines": d.first}}
	if farewell_due(npc):
		return {{"speaker": d.speaker, "lines": d.after}}
	var g: Array = d.greet
	return {{"speaker": d.speaker, "lines": [g[(n - 1) % g.size()]]}}


## Called when the conversation closes (before the talk counter goes up).
static func finish(npc: StringName) -> void:
	if farewell_due(npc):
		GameState.set_flag(StringName("dn_after_" + String(npc)), true)
		GameState.add_item(DATA[npc].gift, 1)
''')

# ---- hooks in Dialogues and Shops (idempotent)
p = f"{R}/systems/dialogues.gd"
s = open(p).read()
if "DescentNpcs" not in s:
    s = s.replace('''	return {"speaker": "...", "lines": ["..."]}


static func _speaker_for''', '''	if DescentNpcs.has(npc):
		return DescentNpcs.conversation(npc)
	return {"speaker": "...", "lines": ["..."]}


static func _speaker_for''', 1)
    s = s.replace('''	if npc == &"ommen" and bool(GameState.get_flag(MARSHAL_FLAG, false)) and not bool(GameState.get_flag(&"ommen_heard_after", false)):
		GameState.set_flag(&"ommen_heard_after", true)
		return''', '''	if DescentNpcs.has(npc):
		DescentNpcs.finish(npc)
	if npc == &"ommen" and bool(GameState.get_flag(MARSHAL_FLAG, false)) and not bool(GameState.get_flag(&"ommen_heard_after", false)):
		GameState.set_flag(&"ommen_heard_after", true)
		return''', 1)
    assert "DescentNpcs.finish" in s and "DescentNpcs.conversation" in s
    open(p, "w").write(s)
p = f"{R}/systems/shops.gd"
s = open(p).read()
if "DescentNpcs" not in s:
    s = s.replace('''	return STOCK.get(shop_id, [])''', '''	if DescentNpcs.SHOPS.has(shop_id):
		return DescentNpcs.SHOPS[shop_id].stock
	return STOCK.get(shop_id, [])''', 1)
    s = s.replace('''	return NAMES.get(shop_id, "WARES")''', '''	if DescentNpcs.SHOPS.has(shop_id):
		return DescentNpcs.SHOPS[shop_id].name
	return NAMES.get(shop_id, "WARES")''', 1)
    assert s.count("DescentNpcs") == 4
    open(p, "w").write(s)
p = f"{R}/systems/dialogues.gd"
s = open(p).read()
if "DescentNpcs.ARCHIVE" not in s and "_archive_ids" not in s:
    s = s.replace("	for id in ARCHIVE:\n		if GameState.item_count(id) > 0", "	for id in _archive_ids():\n		if GameState.item_count(id) > 0", 1)
    s = s.replace("lines4.append(ARCHIVE[id])", "lines4.append(archive_line(id))", 1)
    s = s.replace("static func archive_pending() -> Array:", """static func _archive_ids() -> Array:
	var ids: Array = ARCHIVE.keys()
	ids.append_array(DescentNpcs.ARCHIVE.keys())
	return ids


static func archive_line(id: StringName) -> String:
	return String(ARCHIVE[id]) if ARCHIVE.has(id) else String(DescentNpcs.ARCHIVE.get(id, ""))


static func archive_pending() -> Array:""", 1)
    assert "archive_line(id)" in s and "_archive_ids()" in s
    open(p, "w").write(s)
# generic armour icon routing
p = f"{R}/ui/icons/icon_art.gd"
s = open(p).read()
if 'begins_with("armor_")' not in s:
    s = s.replace('''			elif String(id).begins_with("potion_"):
				_vial(ci)''', '''			elif String(id).begins_with("potion_"):
				_vial(ci)
			elif String(id).begins_with("armor_"):
				_armor_generic(ci, id)''', 1)
    assert 'begins_with("armor_")' in s
    open(p, "w").write(s)
print("descent2 ok", len(D.ARMORS), len(D.ITEMS), len(D.NPCS))


# ---- a relic from every main boss of the Descent
EFFECTS = [("focus_gain", "Focus builds %d%% faster.", [1.5, 1.6, 1.7, 1.8]),
           ("weapon_status", "Your weapon's status builds %d%% faster.", [1.6, 1.7, 1.8, 1.9]),
           ("status_resist", "Resist %d%% of every status buildup.", [0.35, 0.4, 0.45, 0.5]),
           ("ember_gain", "Foes pay %d%% more embers.", [1.4, 1.5, 1.6, 1.7]),
           ("flask_heal", "Ember Vials heal %d%% more.", [1.7, 1.8, 1.9, 2.0]),
           ("parry_focus", "A parry gives %d extra focus.", [35.0, 40.0, 45.0, 50.0])]
NAMES = D.RELIC_NAMES if hasattr(D, "RELIC_NAMES") else ["Veyl's Knucklebone", "Ulme's Drip-Candle", "Vorne's Seal", "Sylve's Heartwood", "Mordant's Ledger", "Sorrel's Compass",
         "Orm's Eyepiece", "Anaxe's Hammer-Charm", "Silence's Veil-Pin", "The Sovereign's Pale Crown", "Wend's Oath-Knot"]
rel_defs = []
rel_ids = []
for i, mp in enumerate(XD.MAPS):
    b = XD.BOSSES[i][2]
    rid = "relic_x_" + b["id"]
    ef, tmpl, vals = EFFECTS[i % 6]
    val = vals[(i // 6 + i) % 4]
    shown = int(round((val - 1.0) * 100)) if ef in ("focus_gain", "weapon_status", "ember_gain", "flask_heal") else (int(round(val * 100)) if ef == "status_resist" else int(val))
    desc = tmpl % shown
    item(rid, NAMES[i], desc + " " + b["lore"], col(b["trim"]), 1, 0, 0.0, 1)
    rel_ids.append(rid)
    rel_defs.append((rid, NAMES[i], desc, ef, val))
    # make the main boss drop it
    ep = f"{R}/data/enemies/{b['id']}.tres"
    t = open(ep).read()
    t = t.replace('path="res://data/items/ember_shard.tres" id="drop"', f'path="res://data/items/{rid}.tres" id="drop"')
    open(ep, "w").write(t)
patch_ids(f"{R}/systems/items/items.gd", rel_ids)
rp = f"{R}/systems/relics.gd"
s = open(rp).read()
add = [r for r in rel_defs if f'&"{r[0]}"' not in s]
if add:
    ins = "".join(f'\t&"{r[0]}": {{"title": "{q(r[1])}", "desc": "{q(r[2])}", "effect": "{r[3]}", "value": {r[4]}}},\n' for r in add)
    s = s.replace("\n}\nconst IDS", "\n" + ins.rstrip("\n") + "\n}\nconst IDS", 1)
    open(rp, "w").write(s)
s = open(rp).read()
_m = re.search(r"const IDS: Array\[StringName\] = \[.*?\]", s, flags=re.S)
_missing = [r[0] for r in rel_defs if f'&"{r[0]}"' not in _m.group(0)]
if _missing:
    _new = _m.group(0)[:-1].rstrip().rstrip(",") + ", " + ", ".join(f'&"{i}"' for i in _missing) + "]"
    open(rp, "w").write(s.replace(_m.group(0), _new, 1))
p = f"{R}/ui/icons/icon_art.gd"
s = open(p).read()
if 'begins_with("relic_x_")' not in s:
    s = s.replace('''			elif String(id).begins_with("armor_"):''', '''			elif String(id).begins_with("relic_x_"):
				_relic(ci, id, t)
			elif String(id).begins_with("armor_"):''', 1)
    open(p, "w").write(s)
print("relics ok", len(rel_ids))
