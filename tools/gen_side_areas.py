#!/usr/bin/env python3
"""Generates the side-area content: the two mini-bosses (Cellarer Grume, Sexton Hale), their
attacks, data and scenes. Levels are generated by tools/levels/gen_side_levels.py.
Run:  python3 tools/gen_side_areas.py"""
import os
R = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

def attack(id_, name, anim, su, act, rec, dmg, kb, parry, hsize, hoff, proj=0.0, amin=0, amax=60, w=1.0,
           status=None, hs=0.1, shake=5.0, track=True, lunge=0.0, lstart=0, lframes=0):
    s = f'''[gd_resource type="Resource" script_class="AttackData" load_steps=2 format=3]

[ext_resource type="Script" path="res://systems/combat/attack_data.gd" id="1_attack"]

[resource]
script = ExtResource("1_attack")
id = &"{id_}"
display_name = "{name}"
animation = &"{anim}"
startup_frames = {su}
active_frames = {act}
recovery_frames = {rec}
chain_open_frame = -1
dodge_cancel_frame = -1
damage = {dmg:.1f}
poise_damage = 0.0
stamina_cost = 0.0
knockback = Vector2({kb[0]}, {kb[1]})
parryable = {"true" if parry else "false"}
hitbox_size = Vector2({hsize[0]}, {hsize[1]})
hitbox_offset = Vector2({hoff[0]}, {hoff[1]})
lunge_speed = {lunge:.1f}
lunge_start_frame = {lstart}
lunge_frames = {lframes}
track_during_startup = {"true" if track else "false"}
projectile_speed = {proj}
projectile_offset = Vector2(14, -34)
hit_stop = {hs}
shake = {shake}
ai_min_range = {amin}
ai_max_range = {amax}
ai_weight = {w}
ai_chain_chance = 1.0
'''
    if status:
        s += f'status = &"{status[0]}"\nstatus_amount = {status[1]}.0\n'
    open(f"{R}/data/attacks/{id_}.tres", "w").write(s)

# --- Cellarer Grume
attack("cellarer_smash", "Cellarer - Cask Smash", "smash", 34, 6, 34, 30, (160, -110), True, (52, 40), (30, -24), amin=0, amax=64, lunge=50, lstart=30, lframes=6)
attack("cellarer_sweep", "Cellarer - Cask Sweep", "sweep", 28, 7, 32, 24, (190, -60), False, (74, 30), (32, -20), amin=0, amax=70, w=0.8)
attack("cellarer_bottle", "Cellarer - Rotgut Bottle", "throw", 30, 2, 34, 12, (80, -40), True, (4, 4), (0, -34), proj=190.0, amin=70, amax=300, w=0.9, status=("poison", 45), hs=0.06, shake=2.0)
attack("cellarer_charge", "Cellarer - Barrel Charge", "charge", 36, 22, 36, 30, (240, -100), False, (34, 46), (20, -24), amin=100, amax=280, w=1.0, lunge=270, lstart=36, lframes=22, shake=7.0)

# --- Sexton Hale
attack("sexton_spade", "Sexton - Spade Strike", "smash", 32, 6, 34, 32, (160, -110), True, (54, 40), (30, -24), amin=0, amax=66, lunge=60, lstart=28, lframes=6, status=("bleed", 30))
attack("sexton_sweep", "Sexton - Cold Sweep", "sweep", 28, 7, 30, 26, (190, -60), False, (80, 30), (34, -20), amin=0, amax=72, w=0.8, status=("frost", 30))
attack("sexton_wisp", "Sexton - Grave Wisp", "throw", 32, 2, 32, 14, (80, -40), True, (4, 4), (0, -34), proj=140.0, amin=70, amax=320, w=1.1, status=("frost", 45), hs=0.06, shake=2.0)
attack("sexton_leap", "Sexton - Burial Leap", "leap", 50, 6, 38, 34, (200, -150), False, (110, 30), (0, -14), track=False, amin=90, amax=300, w=1.1, shake=8.0)

def enemy(id_, name, lore, atks, hp, poise, chase, embers, drop, bonus):
    ext = ['[ext_resource type="Script" path="res://actors/enemies/enemy_data.gd" id="1_enemy"]']
    for i, a in enumerate(atks):
        ext.append(f'[ext_resource type="Resource" path="res://data/attacks/{a}.tres" id="a{i}"]')
    ext.append(f'[ext_resource type="Resource" path="res://data/items/{drop}.tres" id="drop"]')
    ext.append(f'[ext_resource type="Resource" path="res://data/items/{bonus}.tres" id="bonus"]')
    arr = ", ".join(f'ExtResource("a{i}")' for i in range(len(atks)))
    open(f"{R}/data/enemies/{id_}.tres", "w").write(f'''[gd_resource type="Resource" script_class="EnemyData" load_steps={len(ext)+1} format=3]

{chr(10).join(ext)}

[resource]
script = ExtResource("1_enemy")
id = &"{id_}"
display_name = "{name}"
lore = "{lore}"
max_health = {hp:.1f}
max_poise = {poise:.1f}
poise_regen_delay_frames = 120
poise_regen_per_second = 25.0
patrol_speed = 28.0
chase_speed = {chase:.1f}
detection_range = 600.0
vertical_detection = 200.0
leash_range = 99999.0
attacks = [{arr}]
attack_cooldown_min = 40
attack_cooldown_max = 80
recover_frames = 30
backstep_speed = 50.0
stagger_frames = 50
parry_stagger_frames = 120
ember_reward = {embers}
drop_item = ExtResource("drop")
drop_chance = 1.0
drop_count = 1
bonus_drop_item = ExtResource("bonus")
bonus_drop_chance = 1.0
bonus_drop_count = 3
''')

enemy("cellarer_grume", "Grume, the Cellarer", "He kept the manor's cellar for forty years and was told to guard the key with his life. The oath took the second part literally.",
      ["cellarer_smash", "cellarer_sweep", "cellarer_bottle"], 430, 75, 56, 900, "gallery_key", "forge_scrap")
enemy("sexton_hale", "Hale, the Gravewarden", "Sexton of the Pilgrim's Graveyard. He dug every grave on this road and swore he would see each one filled. He has been very thorough.",
      ["sexton_spade", "sexton_sweep", "sexton_wisp"], 540, 85, 58, 1400, "sextons_lantern", "hollow_resin")

def boss(name, boss_id, data, p2, style, hurt=(26, 52), music_pitch=1.0):
    ext = [
        '[ext_resource type="Script" path="res://actors/bosses/boss_base.gd" id="1_boss"]',
        f'[ext_resource type="Resource" path="res://data/enemies/{data}.tres" id="2_data"]',
        '[ext_resource type="Script" path="res://systems/combat/health_component.gd" id="3_health"]',
        '[ext_resource type="Script" path="res://systems/combat/hurtbox.gd" id="4_hurtbox"]',
        '[ext_resource type="Script" path="res://systems/combat/hitbox.gd" id="5_hitbox"]',
        '[ext_resource type="Script" path="res://systems/combat/attack_runner.gd" id="6_runner"]',
        '[ext_resource type="Script" path="res://actors/bosses/brute_visual.gd" id="7_visual"]',
    ]
    for i, a in enumerate(p2):
        ext.append(f'[ext_resource type="Resource" path="res://data/attacks/{a}.tres" id="p{i}"]')
    arr = ", ".join(f'ExtResource("p{i}")' for i in range(len(p2)))
    open(f"{R}/actors/bosses/{data}.tscn", "w").write(f'''[gd_scene load_steps={len(ext)+4} format=3]

{chr(10).join(ext)}

[sub_resource type="RectangleShape2D" id="body_shape"]
size = Vector2(20, 46)

[sub_resource type="RectangleShape2D" id="hurt_shape"]
size = Vector2({hurt[0]}, {hurt[1]})

[sub_resource type="RectangleShape2D" id="hit_shape"]
size = Vector2(56, 44)

[node name="{name}" type="CharacterBody2D"]
collision_layer = 4
collision_mask = 1
floor_snap_length = 4.0
script = ExtResource("1_boss")
data = ExtResource("2_data")
patrol_distance = 0.0
boss_id = &"{boss_id}"
phase2_attacks = [{arr}]
phase2_threshold = 0.5
music_pitch = {music_pitch}

[node name="Body" type="CollisionShape2D" parent="."]
position = Vector2(0, -23)
shape = SubResource("body_shape")

[node name="Health" type="Node" parent="."]
script = ExtResource("3_health")

[node name="Hurtbox" type="Area2D" parent="."]
collision_layer = 16
collision_mask = 0
script = ExtResource("4_hurtbox")

[node name="Shape" type="CollisionShape2D" parent="Hurtbox"]
position = Vector2(0, -26)
shape = SubResource("hurt_shape")

[node name="Hitbox" type="Area2D" parent="."]
collision_layer = 0
collision_mask = 8
script = ExtResource("5_hitbox")

[node name="Shape" type="CollisionShape2D" parent="Hitbox"]
position = Vector2(34, -24)
shape = SubResource("hit_shape")

[node name="AttackRunner" type="Node" parent="." node_paths=PackedStringArray("hitbox")]
script = ExtResource("6_runner")
hitbox = NodePath("../Hitbox")

[node name="Visual" type="Node2D" parent="."]
script = ExtResource("7_visual")
style = {style}
''')

boss("Cellarer", "cellarer", "cellarer_grume", ["cellarer_smash", "cellarer_sweep", "cellarer_bottle", "cellarer_charge"], 0, music_pitch=1.1)
boss("Gravewarden", "gravewarden", "sexton_hale", ["sexton_spade", "sexton_sweep", "sexton_wisp", "sexton_leap"], 1, music_pitch=0.9)
print("ok")
